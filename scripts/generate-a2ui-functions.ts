import { readFile, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import { format } from 'oxfmt'
import { Catalog } from '@a2ui/web_core/catalog'
import { createBasicCatalogFunctions } from '@a2ui/web_core/catalogs/basic/v1'

// Copies the basic-catalog function schemas from @a2ui/web_core, whose catalog entry
// installs a global customElements shim on import, so the package never imports it.
const destination = new URL('../src/a2ui/basicFunctionSchemas.ts', import.meta.url)
const check = process.argv.includes('--check')
const omitted = new Set(['openUrl'])

const functions = createBasicCatalogFunctions().filter(fn => !omitted.has(fn.name))
const { functions: schemas } = new Catalog('functions', '1.0', [], functions).toJson() as {
  functions: Record<string, unknown>
}
const raw = `// Generated by scripts/generate-a2ui-functions.ts from @a2ui/web_core. Do not edit.
export const A2UI_BASIC_FUNCTION_SCHEMAS: Readonly<Record<string, Readonly<Record<string, unknown>>>> = ${JSON.stringify(schemas)}
`
const {
  $schema: _schema,
  ignorePatterns: _ignore,
  ...options
} = JSON.parse(await readFile(new URL('../.oxfmtrc.json', import.meta.url), 'utf8'))
const { code, errors } = await format(fileURLToPath(destination), raw, options)
if (errors.length) throw new Error(`Cannot format function schemas: ${JSON.stringify(errors)}`)

const current = await readFile(destination, 'utf8').catch(error => {
  if (error.code === 'ENOENT') return ''
  throw error
})
if (current !== code) {
  if (check) throw new Error('A2UI function schemas are stale. Run pnpm catalog:generate.')
  await writeFile(destination, code)
}
