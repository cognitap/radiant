import { readFile, writeFile } from 'node:fs/promises'
import { watch } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { format } from 'oxfmt'

const source = new URL('../src/themes/tokens.ts', import.meta.url)
const destination = new URL('../src/themes/baseline.css', import.meta.url)
const check = process.argv.includes('--check')
const watching = process.argv.includes('--watch')

async function generate() {
  // tokens.ts is deliberately self-contained and runs with Node's native type stripping.
  const { flattenTokens, modeStyle, tokenDefaults, typographyRoles } = await import(
    `${source.href}?v=${Date.now()}`
  )
  const styles = modeStyle(flattenTokens(tokenDefaults.light), flattenTokens(tokenDefaults.dark))
  const declarations = Object.entries(styles)
    .map(([variable, value]) => `  ${variable}: ${value};`)
    .join('\n')
  const sourceCss = `/* Generated by scripts/generate-theme-css.mjs from src/themes/tokens.ts. */
/* Run pnpm theme:generate after editing shared defaults. */
:root, :host {
  --_rad-light: initial;
  --_rad-dark: ;
${declarations}
}

@media (prefers-color-scheme: dark) {
  :root, :host {
    --_rad-light: ;
    --_rad-dark: initial;
  }
}

[data-rad-mode='light'] {
  --_rad-light: initial;
  --_rad-dark: ;
}

[data-rad-mode='dark'] {
  --_rad-light: ;
  --_rad-dark: initial;
}

[data-rad-mode='system'] {
  --_rad-light: initial;
  --_rad-dark: ;
}

@media (prefers-color-scheme: dark) {
  [data-rad-mode='system'] {
    --_rad-light: ;
    --_rad-dark: initial;
  }
}
`
  const automatic = {
    'prose-title': 'h1',
    'prose-heading': 'h2',
    'prose-subheading': 'h3, h4, h5, h6',
    'prose-body': 'p, ul, ol',
    'prose-small': 'figcaption',
    'prose-quote': 'blockquote',
    code: 'pre'
  }
  const selectors = role =>
    `:where([data-rad-text="${role}"])${automatic[role] ? `,\n:where([data-rad-prose]) > :where(${automatic[role]}):not(:where([data-rad-text], [data-rad-not-prose], [data-slot]))` : ''}`
  const properties = {
    family: 'font-family',
    size: 'font-size',
    weight: 'font-weight',
    lineHeight: 'line-height',
    letterSpacing: 'letter-spacing',
    measure: 'max-inline-size'
  }
  const roleRules = typographyRoles
    .map(
      role =>
        `${selectors(role)} {\n${Object.entries(properties)
          .map(
            ([key, property]) =>
              `  ${property}: var(--rad-typography-roles-${role}-${key.replace(/[A-Z]/g, x => `-${x.toLowerCase()}`)});`
          )
          .join(
            '\n'
          )}\n  font-optical-sizing: auto;\n  font-synthesis: none;\n  overflow-wrap: anywhere;\n}`
    )
    .join('\n\n')
  const blocks =
    ':where(p, ul, ol, figure, blockquote, pre, h1, h2, h3, h4, h5, h6):not(:where([data-rad-not-prose], [data-slot]))'
  const headings = ':where(h1, h2, h3, h4, h5, h6):not(:where([data-rad-not-prose], [data-slot]))'
  const typeCSS = `/* Generated by scripts/generate-theme-css.mjs; same tokens for both CSS routes. */
@layer components {
  :where([data-rad-type-container]) { container-type: inline-size; container-name: radiant-type; }
  :where([data-rad-prose]) {
    font-family: var(--rad-typography-roles-prose-body-family);
    font-size: var(--rad-typography-roles-prose-body-size);
    font-weight: var(--rad-typography-roles-prose-body-weight);
    line-height: var(--rad-typography-roles-prose-body-line-height);
    letter-spacing: var(--rad-typography-roles-prose-body-letter-spacing);
    max-inline-size: var(--rad-typography-roles-prose-body-measure);
    overflow-wrap: anywhere;
  }
  ${roleRules}
  :where([data-rad-prose]) > ${blocks} { margin-block: 0; }
  :where([data-rad-prose]) > ${blocks} + ${blocks} { margin-block-start: var(--rad-typography-flow-paragraph); }
  :where([data-rad-prose]) > ${blocks} + ${headings} { margin-block-start: var(--rad-typography-flow-heading-before); }
  :where([data-rad-prose]) > ${headings} + ${blocks} { margin-block-start: var(--rad-typography-flow-heading-after); }
  :where([data-rad-prose]) > :where(ul, ol) { padding-inline-start: 1.25em; }
  :where([data-rad-prose]) > :where(pre), :where([data-rad-text="code"]) { overflow: auto; white-space: pre; overflow-wrap: normal; }
  :where([data-rad-prose]) > :where(p, ul, ol, li, blockquote, h1, h2, h3, h4, h5, h6) :where(code):not(:where(pre code)) {
    font-family: var(--rad-typography-roles-code-family); font-size: .9em; font-weight: inherit; line-height: inherit; letter-spacing: 0;
  }
  :where([data-rad-prose]) > :where(pre) > :where(code) { font: inherit; letter-spacing: inherit; }
  @container radiant-type (min-width: 0px) {
    ${typographyRoles.map(role => `${selectors(role)} { font-size: var(--rad-typography-roles-${role}-fluid-size); }`).join('\n')}
  }
}
`
  for (const [filename, contents] of [
    [destination, sourceCss],
    [new URL('../src/typography.css', import.meta.url), typeCSS]
  ]) {
    const { code, errors } = await format(fileURLToPath(filename), contents, {
      printWidth: 100,
      tabWidth: 2,
      singleQuote: true
    })
    if (errors.length) throw new Error(`Cannot format generated CSS: ${JSON.stringify(errors)}`)
    const current = await readFile(filename, 'utf8').catch(error => {
      if (error.code === 'ENOENT') return ''
      throw error
    })
    if (current === code) continue
    if (check) throw new Error('Shared theme CSS is stale. Run pnpm theme:generate.')
    await writeFile(filename, code)
  }
}

await generate()
if (watching) {
  let timer
  watch(new URL('.', source), (_, filename) => {
    if (filename !== 'tokens.ts') return
    clearTimeout(timer)
    timer = setTimeout(() => {
      generate().catch(error => {
        console.error(error)
        process.exitCode = 1
      })
    }, 75)
  })
}
