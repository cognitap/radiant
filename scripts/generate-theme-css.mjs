import { readFile, writeFile } from 'node:fs/promises'
import { watch } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { format } from 'oxfmt'

const source = new URL('../src/themes/tokens.ts', import.meta.url)
const destination = new URL('../src/themes/baseline.css', import.meta.url)
const check = process.argv.includes('--check')
const watching = process.argv.includes('--watch')

async function generate() {
  // tokens.ts is deliberately self-contained and runs with Node's native type stripping.
  const { flattenTokens, modeStyle, tokenDefaults } = await import(`${source.href}?v=${Date.now()}`)
  const styles = modeStyle(flattenTokens(tokenDefaults.light), flattenTokens(tokenDefaults.dark))
  const declarations = Object.entries(styles)
    .map(([variable, value]) => `  ${variable}: ${value};`)
    .join('\n')
  const sourceCss = `/* Generated by scripts/generate-theme-css.mjs from src/themes/tokens.ts. */
/* Run pnpm theme:generate after editing shared defaults. */
:root, :host {
  --_rad-light: initial;
  --_rad-dark: ;
${declarations}
}

@media (prefers-color-scheme: dark) {
  :root, :host {
    --_rad-light: ;
    --_rad-dark: initial;
  }
}

[data-rad-mode='light'] {
  --_rad-light: initial;
  --_rad-dark: ;
}

[data-rad-mode='dark'] {
  --_rad-light: ;
  --_rad-dark: initial;
}

[data-rad-mode='system'] {
  --_rad-light: initial;
  --_rad-dark: ;
}

@media (prefers-color-scheme: dark) {
  [data-rad-mode='system'] {
    --_rad-light: ;
    --_rad-dark: initial;
  }
}
`
  const { code, errors } = await format(fileURLToPath(destination), sourceCss, {
    printWidth: 100,
    tabWidth: 2,
    singleQuote: true
  })
  if (errors.length) throw new Error(`Cannot format generated CSS: ${JSON.stringify(errors)}`)
  const current = await readFile(destination, 'utf8').catch(error => {
    if (error.code === 'ENOENT') return ''
    throw error
  })
  if (current === code) return
  if (check) throw new Error('Shared theme CSS is stale. Run pnpm theme:generate.')
  await writeFile(destination, code)
}

await generate()
if (watching) {
  let timer
  watch(new URL('.', source), (_, filename) => {
    if (filename !== 'tokens.ts') return
    clearTimeout(timer)
    timer = setTimeout(() => {
      generate().catch(error => {
        console.error(error)
        process.exitCode = 1
      })
    }, 75)
  })
}
