import { createLayoutSpring, type LayoutBounds } from './layout.js'
import { resolveSpringParameters } from './config.js'
import type { SpringOptions } from './runtime.js'

export interface SpringLayoutController {
  /** Measure all natural-flow slots together and retarget their persistent springs. */
  measure(): void
  configure(options: SpringOptions): void
  get(slot: HTMLElement): LayoutBounds | undefined
  getVelocity(slot: HTMLElement): LayoutBounds | undefined
  isAnimating(): boolean
  destroy(): void
}
/** Inline property lease. Capture the latest author value on each projection. */
function styles(node: HTMLElement) {
  const previous = new Map<string, { value: string; priority: string }>()
  const written = new Map<string, string>()
  return {
    set(key: string, value: string) {
      if (!written.has(key))
        previous.set(key, {
          value: node.style.getPropertyValue(key),
          priority: node.style.getPropertyPriority(key)
        })
      node.style.setProperty(key, value)
      written.set(key, node.style.getPropertyValue(key))
    },
    restore() {
      for (const [key, value] of written) {
        if (node.style.getPropertyValue(key) !== value) continue
        const saved = previous.get(key)!
        if (saved.value) node.style.setProperty(key, saved.value, saved.priority)
        else node.style.removeProperty(key)
      }
      written.clear()
    }
  }
}
type Entry = {
  part: HTMLElement
  slotStyle: ReturnType<typeof styles>
  partStyle: ReturnType<typeof styles>
  spring: ReturnType<typeof createLayoutSpring>
  target: LayoutBounds
}
/**
 * Direct-child natural-flow slots with one dedicated motion part each.
 * Never clone/reparent a semantic host or scale text, borders or children.
 */
export function bindSpringLayout(
  root: HTMLElement,
  options: SpringOptions = {}
): SpringLayoutController {
  if (options.reducedValue !== undefined)
    throw new TypeError('Layout off mode snaps to measured bounds.')
  const win = root.ownerDocument.defaultView!
  const entries = new Map<HTMLElement, Entry>()
  let currentOptions = { ...options, parameters: resolveSpringParameters(options.parameters) }
  let frame: number | undefined
  let needsMeasure = false
  let destroyed = false
  const resize = new win.ResizeObserver(schedule)
  function contentChanged(records: MutationRecord[]) {
    if (
      records.some(record => {
        // These style mutations are our own projection writes. Other content/style
        // mutations can change natural layout and must be measured as a group.
        if (record.type === 'attributes' && record.attributeName === 'style') {
          if (entries.has(record.target as HTMLElement)) return false
          if (Array.from(entries.values()).some(entry => entry.part === record.target)) return false
        }
        return true
      })
    )
      schedule()
  }
  const mutations = new win.MutationObserver(contentChanged)
  function restore(entry: Entry) {
    entry.partStyle.restore()
    entry.slotStyle.restore()
  }
  function dispose(slot: HTMLElement, entry: Entry) {
    restore(entry)
    entry.spring.destroy()
    resize.unobserve(slot)
    entries.delete(slot)
  }
  function draw() {
    // Preserve external mutations queued by an earlier frame callback before
    // discarding the records generated by our own presentation writes.
    contentChanged(mutations.takeRecords())
    for (const entry of entries.values()) {
      const bounds = entry.spring.get()
      entry.partStyle.set('width', `${Math.max(0, bounds.width)}px`)
      entry.partStyle.set('height', `${Math.max(0, bounds.height)}px`)
      entry.partStyle.set(
        'translate',
        `${bounds.x - entry.target.x}px ${bounds.y - entry.target.y}px`
      )
    }
    mutations.takeRecords()
  }
  function project(slot: HTMLElement, entry: Entry) {
    entry.slotStyle.set('position', 'relative')
    entry.slotStyle.set('box-sizing', 'border-box')
    entry.slotStyle.set('flex', 'none')
    entry.slotStyle.set('width', `${entry.target.width}px`)
    entry.slotStyle.set('height', `${entry.target.height}px`)
    entry.partStyle.set('position', 'absolute')
    entry.partStyle.set('left', '0px')
    entry.partStyle.set('top', '0px')
    entry.partStyle.set('box-sizing', 'border-box')
  }
  function measure() {
    if (destroyed) return
    needsMeasure = false
    for (let ancestor: HTMLElement | null = root; ancestor; ancestor = ancestor.parentElement) {
      const css = win.getComputedStyle(ancestor)
      const matrix = css.transform === 'none' ? undefined : new win.DOMMatrixReadOnly(css.transform)
      if (
        (matrix &&
          (!matrix.is2D || matrix.a !== 1 || matrix.b !== 0 || matrix.c !== 0 || matrix.d !== 1)) ||
        (css.scale !== 'none' && css.scale.split(' ').some(value => Number(value) !== 1)) ||
        (css.rotate !== 'none' && parseFloat(css.rotate) !== 0) ||
        (css.zoom && Number(css.zoom) !== 1) ||
        css.perspective !== 'none'
      )
        throw new TypeError('Layout measurement requires an unscaled, unrotated coordinate space.')
    }
    // Release every reservation before any geometry read. Measuring one item
    // while its siblings are projected would feed animation back into layout.
    entries.forEach(restore)
    const slots = Array.from(root.children).filter(
      (node): node is HTMLElement =>
        node instanceof win.HTMLElement && node.hasAttribute('data-rad-layout-slot')
    )
    for (const [slot, entry] of entries) {
      if (!slots.includes(slot) || slot.firstElementChild !== entry.part) dispose(slot, entry)
    }
    const origin = root.getBoundingClientRect()
    const targets = slots.map(slot => {
      const part = slot.firstElementChild
      if (
        slot.children.length !== 1 ||
        !(part instanceof win.HTMLElement) ||
        !part.hasAttribute('data-rad-layout-part')
      )
        throw new TypeError('Each layout slot requires a first-child data-rad-layout-part.')
      const css = win.getComputedStyle(slot)
      if (
        !['static', 'relative'].includes(css.position) ||
        ['inline', 'contents'].includes(css.display) ||
        [
          'borderLeftWidth',
          'borderTopWidth',
          'borderRightWidth',
          'borderBottomWidth',
          'paddingLeft',
          'paddingTop',
          'paddingRight',
          'paddingBottom'
        ].some(key => parseFloat(css[key as keyof CSSStyleDeclaration] as string) > 0)
      )
        throw new TypeError('Layout slots must be unpadded, borderless normal-flow wrappers.')
      const partCss = win.getComputedStyle(part)
      if (
        !['static', 'relative'].includes(partCss.position) ||
        [css, partCss].some(
          style =>
            style.transform !== 'none' ||
            style.translate !== 'none' ||
            style.scale !== 'none' ||
            style.rotate !== 'none'
        ) ||
        ['marginLeft', 'marginTop', 'marginRight', 'marginBottom'].some(
          key => parseFloat(partCss[key as keyof CSSStyleDeclaration] as string) !== 0
        )
      )
        throw new TypeError(
          'Use dedicated transform-free layout slots and motion parts with no part margins.'
        )
      const rect = slot.getBoundingClientRect()
      return {
        slot,
        part,
        bounds: {
          x: rect.left - origin.left - root.clientLeft + root.scrollLeft,
          y: rect.top - origin.top - root.clientTop + root.scrollTop,
          width: rect.width,
          height: rect.height
        }
      }
    })
    for (const { slot, part, bounds } of targets) {
      let entry = entries.get(slot)
      if (!entry) {
        entry = {
          part,
          slotStyle: styles(slot),
          partStyle: styles(part),
          spring: createLayoutSpring(bounds, currentOptions),
          target: bounds
        }
        entries.set(slot, entry)
        resize.observe(slot)
      } else {
        entry.target = bounds
        entry.spring.to(bounds)
      }
      project(slot, entry)
    }
    mutations.takeRecords()
    draw()
    if (controller.isAnimating()) requestFrame()
    else entries.forEach(restore)
    mutations.takeRecords()
  }
  function tick() {
    frame = undefined
    if (destroyed) return
    if (needsMeasure) measure()
    else draw()
    if (controller.isAnimating()) requestFrame()
    else {
      entries.forEach(restore)
      mutations.takeRecords()
    }
  }
  function requestFrame() {
    if (frame === undefined) frame = win.requestAnimationFrame(tick)
  }
  function schedule() {
    if (destroyed) return
    needsMeasure = true
    requestFrame()
  }
  const controller: SpringLayoutController = {
    measure,
    configure(next) {
      if (destroyed) return
      if (next.reducedValue !== undefined)
        throw new TypeError('Layout off mode snaps to measured bounds.')
      // Validate before changing any entry or remembering options for new slots.
      currentOptions = {
        ...currentOptions,
        ...next,
        parameters: resolveSpringParameters(next.parameters, currentOptions.parameters)
      }
      entries.forEach(entry => entry.spring.configure(next))
      if (controller.isAnimating()) {
        draw()
        requestFrame()
      } else {
        entries.forEach(restore)
        mutations.takeRecords()
      }
    },
    get: slot => entries.get(slot)?.spring.get(),
    getVelocity: slot => entries.get(slot)?.spring.getVelocity(),
    isAnimating: () => Array.from(entries.values()).some(entry => entry.spring.isAnimating()),
    destroy() {
      if (destroyed) return
      destroyed = true
      if (frame !== undefined) win.cancelAnimationFrame(frame)
      mutations.disconnect()
      resize.disconnect()
      root.removeEventListener('load', schedule, true)
      root.removeEventListener('scroll', schedule, true)
      win.removeEventListener('resize', schedule)
      root.ownerDocument.fonts?.removeEventListener('loadingdone', schedule)
      for (const [slot, entry] of entries) dispose(slot, entry)
    }
  }
  try {
    measure()
  } catch (error) {
    controller.destroy()
    throw error
  }
  resize.observe(root)
  mutations.observe(root, {
    subtree: true,
    childList: true,
    characterData: true,
    attributes: true,
    attributeFilter: ['class', 'style', 'hidden', 'open']
  })
  root.addEventListener('load', schedule, true)
  root.addEventListener('scroll', schedule, true)
  win.addEventListener('resize', schedule)
  root.ownerDocument.fonts?.addEventListener('loadingdone', schedule)
  return controller
}
